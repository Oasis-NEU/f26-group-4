// Just the names, for pickers that only deal in names.
export const COUNTRY_NAMES: string[] = COUNTRIES.map((country) => country.name);

// Compares two names ignoring capitals and spaces.
function sameName(first: string, second: string): boolean {
  return first.trim().toLowerCase() === second.trim().toLowerCase();
}

// The two-letter code for a country name, or an empty string if we don't know it.
export function countryCode(name: string): string {
  for (const country of COUNTRIES) {
    if (sameName(country.name, name)) {
      return country.code;
    }
  }

  return '';
}

// The flag emoji for a country name, e.g. "France" -> 🇫🇷.
//
// A flag emoji is just the country's two letters written in a special alphabet
// called "regional indicators". Those letters sit at a fixed distance from the
// normal A-Z in the emoji table, so adding that distance to each letter turns
// "FR" into the French flag. That's why this doesn't need a list of 195 flags.
export function countryFlag(name: string): string {
  const code = countryCode(name);

  if (code === '') {
    return '';
  }

  // 127397 is the gap between a normal capital letter and its regional
  // indicator version.
  const first = String.fromCodePoint(code.charCodeAt(0) + 127397);
  const second = String.fromCodePoint(code.charCodeAt(1) + 127397);

  return first + second;
}

// Countries whose name starts with, or contains, the search text. Used by the
// country picker: typing "jap" finds Japan. Starts-with matches come first so
// "ind" offers India before "British Indian Ocean Territory" style matches.
export function searchCountries(query: string): Country[] {
  const text = query.trim().toLowerCase();

  if (text === '') {
    return COUNTRIES;
  }

  const startsWith: Country[] = [];
  const contains: Country[] = [];

  for (const country of COUNTRIES) {
    const name = country.name.toLowerCase();

    if (name.startsWith(text)) {
      startsWith.push(country);
    } else if (name.includes(text)) {
      contains.push(country);
    }
  }

  return [...startsWith, ...contains];
}
